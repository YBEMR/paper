"""Pure deadline fixtures; mock SAFE receipts are not thermal evidence.

Schedules below are written by hand, never generated by a search or obtained
from historical SAFE results.  TEST_ONLY mutations isolate exact boundary
semantics and never change the production configuration or research inputs.
"""
from copy import deepcopy
from fractions import Fraction as F
import unittest
from unittest.mock import patch

import deadline_entry as entry
from execution_status import classify_execution
from run_four_method_comparison import canonical
from schedules import validate_schedule


def hand_schedule(instance):
    """A small complete all-H schedule, with legal 5 ms start times."""
    choices = {
        'A.pre': ('CPU1', '0'), 'A.main': ('NPU0', '10'),
        'A.post': ('CPU1', '40'), 'B.pre': ('CPU2', '0'),
        'B.main': ('NPU0', '40'), 'B.post': ('CPU2', '75'),
        'C.pre': ('CPU2', '0'), 'C.main': ('GPU0', '15'),
        'C.post': ('CPU2', '60'),
    }
    return {'scenes': {
        scene['id']: [dict(stage_id=stage['id'], unit=choices[stage['shared_stage_id']][0],
                           opp='H', start_ms=choices[stage['shared_stage_id']][1])
                      for stage in scene['stage_instances']]
        for scene in instance['scenarios']}}


def mocked_result(candidate=None):
    """A synthetic already-returned record, not an accepted research output."""
    safe = candidate is not None
    return {'state': 'SAFE' if safe else 'UNRESOLVED',
        'reason': 'DECLARED_SEARCH_COMPLETED',
        'safe_candidate': deepcopy(candidate),
        'safe_upper_bound_J': '1' if safe else None,
        'evaluation': {'state': 'SAFE', 'MOCK_ONLY': True} if safe else None,
        'evaluations': [], 'independently_proven_optimal': False,
        'independently_proven_infeasible': False}


def mocked_record(result):
    safe = result.get('safe_candidate') is not None
    context = {'input_identity_valid': True, 'source_identity_valid': True,
        'current_request_identity_valid': True, 'cutoff_s': 300,
        'hard_errors': [], 'observed_numerical_rejection': False,
        'worker_isolation': 'NOT_APPLICABLE', 'prior_requests_complete': True,
        'completion_verified': True, 'root_deadline_confirmed': False,
        'deadline_causal_trace': False, 'last_request': {'state': 'NONE'},
        'safe_receipt': ({'verified': True, 'identity_valid': True,
                         'complete': True, 'formed_at_s': 10,
                         'energy_upper_J': '1'} if safe else None),
        'thermal_unresolved': False}
    execution = classify_execution(result, context)
    return {'context': context, 'execution': execution,
        'usable_U_J': execution['usable_U_J'],
        'raw_reported_U_J': result.get('safe_upper_bound_J')}


class DeadlineBoundaryTests(unittest.TestCase):
    def fixture(self):
        declaration, triple = entry.input_declaration(entry.PROBLEMS[0])
        raw, config, instance = deepcopy(triple)
        return declaration, raw, config, instance, hand_schedule(instance)

    def bind(self, declaration, raw, config, instance, result):
        with patch.object(entry, 'fresh_input', return_value=(raw, config, instance)):
            return entry.bind_current_legality(mocked_record(result), result, declaration)

    def test_01_hand_written_complete_schedule_is_currently_legal(self):
        declaration, raw, config, instance, candidate = self.fixture()
        checked = validate_schedule(instance, candidate)
        self.assertEqual(checked['state'], 'SCHEDULE_VALID_THERMAL_UNCHECKED')
        result = mocked_result(candidate)
        original = deepcopy(result)
        record = self.bind(declaration, raw, config, instance, result)
        self.assertTrue(record['current_schedule_audit']['passed'])
        self.assertFalse(record['current_schedule_audit']['new_thermal_evaluation'])
        self.assertEqual(record['usable_U_J'], '1')
        self.assertEqual(result, original)
        self.assertTrue(record['current_schedule_audit']['checks'])

    def test_02_noninteger_finish_exactly_at_deadline_is_legal(self):
        declaration, raw, config, instance, candidate = self.fixture()
        for mode in instance['stage_modes']['A.post']:
            if mode['unit_id'] == 'CPU1' and mode['opp_id'] == 'H':
                mode['duration_ms'] = '11/2'
        for scene in instance['scenarios']:
            for request in scene['requests']:
                if request['application'] == 'A':
                    request['deadline_ms'] = '91/2'
        checked = validate_schedule(instance, candidate)
        self.assertEqual(checked['state'], 'SCHEDULE_VALID_THERMAL_UNCHECKED')
        for scene in checked['scenes'].values():
            rows = [r for r in scene['rows'] if r['shared_stage_id'] == 'A.post']
            self.assertEqual(F(rows[0]['end_ms']), F(91, 2))
        declaration['input_sha256'] = canonical(instance)
        declaration['input_identities']['input_sha256'] = declaration['input_sha256']
        record = self.bind(declaration, raw, config, instance, mocked_result(candidate))
        self.assertTrue(record['current_schedule_audit']['passed'])
        self.assertEqual(record['usable_U_J'], '1')

    def test_03_fractionally_late_finish_is_not_rounded_into_deadline(self):
        declaration, raw, config, instance, candidate = self.fixture()
        for mode in instance['stage_modes']['A.post']:
            if mode['unit_id'] == 'CPU1' and mode['opp_id'] == 'H':
                mode['duration_ms'] = '11/2'
        for scene in instance['scenarios']:
            for request in scene['requests']:
                if request['application'] == 'A':
                    request['deadline_ms'] = '454999/10000'
        checked = validate_schedule(instance, candidate)
        self.assertEqual(checked['reason'], 'REQUEST_DEADLINE_EXCEEDED')
        declaration['input_sha256'] = canonical(instance)
        declaration['input_identities']['input_sha256'] = declaration['input_sha256']
        result = mocked_result(candidate)
        original = deepcopy(result)
        record = self.bind(declaration, raw, config, instance, result)
        self.assertFalse(record['current_schedule_audit']['passed'])
        self.assertIsNone(record['usable_U_J'])
        self.assertIsNone(record['execution']['usable_U_J'])
        self.assertEqual(record['execution']['execution_status'], 'TECHNICAL_FAILURE_CONFIRMED')
        self.assertEqual(result, original)

    def test_04_old_loose_deadline_schedule_cannot_be_relabelled_safe(self):
        declaration, raw, config, instance, candidate = self.fixture()
        for rows in candidate['scenes'].values():
            for row in rows:
                if row['stage_id'].endswith('::A.post'):
                    row['start_ms'] = '100'
        loose = deepcopy(instance)
        for scene in loose['scenarios']:
            for request in scene['requests']:
                request['deadline_ms'] = str(F(request['release_ms']) +
                    F('1.3') * F(request['reference_CPU_H_chain_ms']))
        self.assertEqual(validate_schedule(loose, candidate)['state'],
                         'SCHEDULE_VALID_THERMAL_UNCHECKED')
        self.assertEqual(validate_schedule(instance, candidate)['reason'],
                         'REQUEST_DEADLINE_EXCEEDED')
        result = mocked_result(candidate)
        result['evaluation'].update(problem_id=declaration['problem_id'],
            legality={'state': 'SCHEDULE_VALID_THERMAL_UNCHECKED'})
        record = self.bind(declaration, raw, config, instance, result)
        self.assertFalse(record['current_schedule_audit']['passed'])
        self.assertIsNone(record['usable_U_J'])

    def test_05_accepted_intermediate_candidate_also_obeys_current_deadline(self):
        declaration, raw, config, instance, candidate = self.fixture()
        late = deepcopy(candidate)
        for rows in late['scenes'].values():
            for row in rows:
                if row['stage_id'].endswith('::A.post'):
                    row['start_ms'] = '100'
        result = mocked_result(candidate)
        result['evaluations'] = [{'accepted_safe': True, 'candidate': late,
            'evaluation': {'state': 'SAFE', 'MOCK_ONLY': True}}]
        record = self.bind(declaration, raw, config, instance, result)
        self.assertFalse(record['current_schedule_audit']['passed'])
        # Preserve a separately valid final witness, while the incorrect
        # accepted intermediate record still blocks the method/batch.
        self.assertEqual(record['usable_U_J'], '1')
        self.assertEqual(record['execution']['execution_status'], 'TECHNICAL_FAILURE_CONFIRMED')

    def test_06_rejected_candidate_does_not_invalidate_legal_final_safe(self):
        declaration, raw, config, instance, candidate = self.fixture()
        late = deepcopy(candidate)
        for rows in late['scenes'].values():
            for row in rows:
                if row['stage_id'].endswith('::A.post'):
                    row['start_ms'] = '100'
        result = mocked_result(candidate)
        result['evaluations'] = [{'accepted_safe': False, 'candidate': late,
            'evaluation': {'state': 'INVALID_SCHEDULE', 'MOCK_ONLY': True}}]
        record = self.bind(declaration, raw, config, instance, result)
        self.assertTrue(record['current_schedule_audit']['passed'])
        self.assertEqual(record['usable_U_J'], '1')

    def test_07_current_input_hash_mismatch_refuses_usable_energy(self):
        declaration, raw, config, instance, candidate = self.fixture()
        declaration['input_sha256'] = '0' * 64
        try:
            record = self.bind(declaration, raw, config, instance, mocked_result(candidate))
        except ValueError:
            return
        self.assertFalse(record['current_schedule_audit']['passed'])
        self.assertIsNone(record['usable_U_J'])

    def test_08_no_safe_result_does_not_create_a_witness_or_energy(self):
        declaration, raw, config, instance, candidate = self.fixture()
        result = mocked_result()
        original = deepcopy(result)
        record = self.bind(declaration, raw, config, instance, result)
        self.assertTrue(record['current_schedule_audit']['passed'])
        self.assertEqual(record['current_schedule_audit']['checks'], [])
        self.assertIsNone(record['usable_U_J'])
        self.assertFalse(record['execution']['independently_proven_infeasible'])
        self.assertFalse(record['execution']['independently_proven_optimal'])
        self.assertEqual(result, original)

    def test_09_solver_reported_infeasible_is_not_an_independent_certificate(self):
        result = mocked_result()
        result['reason'] = 'SOLVER_REPORTED_INFEASIBLE'
        record = mocked_record(result)
        self.assertEqual(record['execution']['execution_status'], 'NORMAL_COMPLETION')
        self.assertIsNone(record['usable_U_J'])
        self.assertFalse(record['execution']['independently_proven_infeasible'])
        self.assertFalse(record['execution']['independently_proven_optimal'])


if __name__ == '__main__':
    unittest.main()
