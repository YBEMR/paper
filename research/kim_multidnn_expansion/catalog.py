def legality_rows():
    rows=[]
    frozen, _ = _build()
    for ident,dep in frozen["deployments"].items():
        stages=dep["stages"]
        loads={r:sum(resource==r for chain in stages.values() for resource,_,_ in chain)
               for r in ("DLA0","DLA1")}
        rows.append({"deployment":ident,"app0":dep["per_app_candidate_ids"][0],
                     "app1":dep["per_app_candidate_ids"][1],"app2":dep["per_app_candidate_ids"][2],
                     "app3":dep["per_app_candidate_ids"][3],"resident_dla_stages":sum(loads.values()),
                     "dla0_resident_stages":loads["DLA0"],"dla1_resident_stages":loads["DLA1"],
                     "full_layer_cover":True,"all_graph_edges_forwarded":True,
                     "cross_scene_resident":True,"shared_dla_clock":True,
                     "graph_operator_screen":"PASS_ABSTRACT_ONLY","tensorrt_execution_verified":False,
                     "physical_stages":json.dumps(stages,separators=(",",":"))})
    return rows


def stage_feature_rows():
    """Generate canonical per-network stages at all 27 clocks, without events.

    Mirrored resource assignments use exactly the same times and powers; the
    experiment regenerates complete chains for each actual deployment.
    """
    rows=[]
    for app,specs in SPECS.items():
        ops,heads,_=graph(app)
        for name,chain,_ in specs:
            view=deepcopy(BASE)
            view["deployments"]={"candidate":{"stages":deepcopy(BASE["deployments"]["A"]["stages"])}}
            view["deployments"]["candidate"]["stages"][app]=[list(row) for row in chain]
            for opp in OPPS:
                generated=build_chains(PLATFORM,view,"candidate",opp)[int(app)]
                for index,stage in enumerate(generated):
                    first=last=None; mac=traffic=handoff=None; live=[]
                    if index>=2 and index<2+2*len(chain):
                        k=(index-2)//2
                        _,first,last=chain[k]
                        if index%2==0:
                            mac=sum(op.mac for op in ops[first:last+1])
                            traffic=sum(op.traffic_bytes for op in ops[first:last+1])
                        else:
                            live=_live_layers(ops,heads,last)
                            handoff=live_bytes(ops,heads,last,PLATFORM["image"]["bytes_per_scalar"])
                            first=None
                    elif index==1:
                        handoff=PLATFORM["image"]["side"]**2*PLATFORM["image"]["channels"]*PLATFORM["image"]["bytes_per_scalar"]
                    rows.append({"candidate":name,"app":int(app),"opp":opp,"chain_index":index,
                                 "name":stage.name,"resource":stage.resource,"first_layer":first,
                                 "last_layer":last,"mac":mac,"traffic_bytes":traffic,
                                 "forwarded_layer_outputs":"|".join(map(str,live)),"handoff_bytes":handoff,
                                 "duration_ns":stage.duration_ns,"active_w":stage.activity_w})
    return rows


def write_json(path, value):
    path.write_text(json.dumps(value,ensure_ascii=False,allow_nan=False,indent=2)+"\n",encoding="utf-8",newline="\n")


def write_csv(path, rows):
    with path.open("w",encoding="utf-8",newline="") as stream:
        writer=csv.DictWriter(stream,fieldnames=list(rows[0]),lineterminator="\n")
        writer.writeheader(); writer.writerows(rows)


def main():
    frozen,meta=_build()
    write_json(HERE/"expanded_input.json",frozen)
    write_json(HERE/"catalog.json",meta)
    write_csv(HERE/"legality.csv",legality_rows())
    stage_rows=stage_feature_rows()
    write_csv(HERE/"stage_features.csv",stage_rows)
    print(json.dumps({"status":"ABSTRACT_CHECKS_PASS","counts":meta["counts"],
                      "stage_feature_rows":len(stage_rows),"tensorrt_execution_verified":False},indent=2))


if __name__ == "__main__":
    main()
