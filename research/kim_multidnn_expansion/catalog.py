DLA_ABSTRACT_KINDS = {"conv", "activation", "pool", "shortcut"}


def _swap(stages):
    return {app: [["DLA1" if r == "DLA0" else "DLA0" if r == "DLA1" else r, a, b]
                  for r, a, b in chain] for app, chain in stages.items()}


def _key(stages):
    return tuple((app, tuple(tuple(row) for row in stages[app])) for app in sorted(stages))


def _canonical(stages):
    # Lexicographic representative == first encountered DLA stage uses DLA0.
    return min((stages, _swap(stages)), key=_key)


def _node_vector(value):
    return list(value) if isinstance(value, list) else [value] * 4


def symmetry_checks():
    """Check every numerical condition used in the global DLA label symmetry.

    Event-rule argument: queues use readiness, release, application priority,
    stage index and request ID; resource labels are not scheduling priorities.
    All same-time completions enqueue before any next dispatch. A global DLA
    permutation therefore only renames the two queues and thermal coordinates.
    """
    therm, power = PLATFORM["thermal"], PLATFORM["power"]
    permutation = (0, 1, 3, 2)
    checks = {}
    for field in ("capacity_J_K", "ambient_conductance_W_K", "initial_C", "limits_C"):
        values = _node_vector(therm[field])
        checks[field] = values == [values[i] for i in permutation]
    matrix = therm["pair_conductance_W_K"]
    checks["pair_conductance_W_K"] = matrix == [[matrix[i][j] for j in permutation]
                                                 for i in permutation]
    for field in ("board_heat_fraction", "transfer_heat_fraction"):
        values = power[field]
        checks[field] = values == [values[i] for i in permutation]
    checks["DLA_node_weights"] = power["DLA_node_weights"] == list(reversed(power["DLA_node_weights"]))
    checks["one_service_parameter_set"] = "DLA" in PLATFORM["service"] and all(
        name not in PLATFORM["service"] for name in ("DLA0", "DLA1"))
    checks["shared_frequency_domain"] = BASE["clock_policy"]["domain_members"]["DLA"] == ["DLA0", "DLA1"]
    checks["four_thermal_nodes"] = therm["node_order"] == ["CPU", "GPU", "DLA0", "DLA1"]
    if not all(checks.values()):
        raise ValueError("DLA global-swap reduction invalid: " + str(checks))
    return checks


def graph(app):
    image = PLATFORM["image"]
    blocks = PLATFORM["architecture_reference"]["graphs"][app]["blocks"]
    ops, heads = graph_features(tuple(tuple(row) for row in blocks), image["side"],
                               image["channels"], image["bytes_per_scalar"])
    kinds = []
    for row in blocks:
        kinds.append(row[0])
        if row[0] == "conv" and row[-1]:
            kinds.append("activation")
    assert len(kinds) == len(ops) == BASE["applications"][int(app)]["layers"]
    return ops, heads, kinds


def _live_layers(ops, heads, cut):
    return sorted({j for op in ops[cut+1:] for j in op.inputs if 0 <= j <= cut}
                  | {j for j in heads if j <= cut})


def check_chain(app, chain):
    ops, heads, kinds = graph(app)
    resources = tuple("DLA" if r.startswith("DLA") else r for r, _, _ in chain)
    assert resources in ALLOWED_STRUCTURES and chain[-1][0] == "GPU"
    cursor = 0
    cuts = []
    for resource, first, last in chain:
        assert resource in ("GPU", "DLA0", "DLA1")
        assert first == cursor and first <= last < len(ops)
        cursor = last + 1
        if resource.startswith("DLA"):
            assert set(kinds[first:last+1]) <= DLA_ABSTRACT_KINDS
        if last < len(ops)-1:
            assert not (kinds[last] == "conv" and kinds[last+1] == "activation")
            live = _live_layers(ops, heads, last)
            expected = PLATFORM["image"]["bytes_per_scalar"] * sum(prod(ops[j].shape) for j in live)
            assert expected == live_bytes(ops, heads, last, PLATFORM["image"]["bytes_per_scalar"])
            cuts.append({"after_layer":last, "live_layers":live, "bytes":expected})
    assert cursor == len(ops)
    dlas = [r for r, _, _ in chain if r.startswith("DLA")]
    if len(dlas) == 2:
        assert set(dlas) == {"DLA0", "DLA1"}
    assert sum(sum(ops[j].mac for j in range(a,b+1)) for _,a,b in chain) == sum(op.mac for op in ops)
    # Every dependency crossing a partition is forwarded by every intervening
    # handoff. Outputs remain live for all later consumers, including heads.
    for consumer, op in enumerate(ops):
        for producer in op.inputs:
            assert producer < consumer
            for cut in cuts:
                if 0 <= producer <= cut["after_layer"] < consumer:
                    assert producer in cut["live_layers"]
    return cuts


def _variants(spec):
    name, chain, source = spec
    canonical = [[r,a,b] for r,a,b in chain]
    variants = [canonical]
    if any(r.startswith("DLA") for r,_,_ in chain):
        variants.append(_swap({"x":canonical})["x"])
    return [(name, variant, source) for variant in variants]


@lru_cache(maxsize=1)
def _build():
    symmetry = symmetry_checks()
    all_structures = list(product(*(SPECS[str(i)] for i in range(4))))
    rejected = []
    physical = []
    for specs in all_structures:
        resident = sum(r.startswith("DLA") for _,chain,_ in specs for r,_,_ in chain)
        ids = [s[0] for s in specs]
        if resident > 4:
            rejected.append({"per_app_candidate_ids":ids, "resident_dla_stages":resident,
                             "reason":"all-resident DLA stage cap exceeded"})
            continue
        for variants in product(*(_variants(s) for s in specs)):
            stages = {str(i):deepcopy(v[1]) for i,v in enumerate(variants)}
            physical.append({"stages":stages, "per_app_candidate_ids":ids,
                             "resident_dla_stages":resident})
    canonical = {}
    for row in physical:
        representative = _canonical(row["stages"])
        canonical[_key(representative)] = dict(row,stages=representative)
    legacy_keys = {_key(BASE["deployments"][d]["stages"]):d for d in ("A","C")}
    deployments = {}
    lookup = {}
    next_id = 0
    for key,row in sorted(canonical.items()):
        if key in legacy_keys:
            ident = legacy_keys[key]
            deployment = deepcopy(BASE["deployments"][ident])
        else:
            ident = f"D{next_id:03d}"
            next_id += 1
            deployment = {"case":"small source-bounded synthetic deployment combination",
                          "stages":deepcopy(row["stages"]),
                          "resident_dla_engines":row["resident_dla_stages"]}
        deployment["per_app_candidate_ids"] = row["per_app_candidate_ids"]
        deployment["resident_dla_stages"] = row["resident_dla_stages"]
        deployment["engine_validation"] = "NOT_TENSORRT_COMPILED_OR_EXECUTED"
        deployments[ident] = deployment
        lookup[key] = ident
    # Baselines first; the remainder are deterministic round-robin strata by
    # YOLOv3 structure. This is an evaluation order, not objective-based pruning.
    groups = [[d for d in sorted(deployments) if d not in ("A","C") and
               deployments[d]["per_app_candidate_ids"][3] == kind]
              for kind in ("v3_E", "v3_A36", "v3_C36_78")]
    order = ["A","C"] + [d for group in zip_longest(*groups) for d in group if d is not None]
    deployments = {d:deployments[d] for d in order}
    aliases = []
    for index,row in enumerate(sorted(physical,key=lambda r:_key(r["stages"]))):
        target = lookup[_key(_canonical(row["stages"]))]
        aliases.append({"physical_id":f"P{index:03d}", "representative":target,
                        "global_swap_needed":_key(row["stages"]) != _key(deployments[target]["stages"]),
                        "stages":row["stages"], "per_app_candidate_ids":row["per_app_candidate_ids"]})
    assert len(physical) == 161 and len(deployments) == 81 and len(rejected) == 5
    assert len(set(order)) == len(deployments)
    for d in ("A","C"):
        assert deployments[d]["stages"] == BASE["deployments"][d]["stages"]
    for ident, dep in deployments.items():
        resident = sum(r.startswith("DLA") for chain in dep["stages"].values() for r,_,_ in chain)
        assert resident == dep["resident_dla_stages"] == dep["resident_dla_engines"] <= 4
        for app,chain in dep["stages"].items():
            check_chain(app,chain)
    frozen = deepcopy(BASE)
    frozen["deployments"] = deployments
    frozen["metadata"]["expansion"] = {
        "base_commit":BASE_COMMIT, "synthetic_platform":"kim_synthetic_platform_v1/platform.json",
        "numerical_authority":"The unchanged synthetic-v1 platform and profiles; old null intake fields are historical metadata only.",
        "physical_clock_policy":"One CPU/GPU/shared-DLA triplet per scene, carried through idle and final tail.",
        "precision":"Fixed existing FP16/ReLU graph proxy; numerical detection accuracy unmeasured.",
        "residency":"All four networks stay loaded for all scenes; no migration; <=4 DLA stages in total.",
        "scope":"31 legal structure combinations, 161 physical assignments, 81 global-DLA-swap classes; not Kim's full measured candidate library.",
    }
    specs_metadata = []
    for app,specs in SPECS.items():
        for name,chain,source in specs:
            specs_metadata.append({"id":name,"app":int(app),"network":BASE["applications"][int(app)]["network"],
                                   "canonical_stages":chain,"source_category":source,
                                   "tensor_handoffs":check_chain(app,chain),
                                   "validation":"abstract graph/rule checked; no TensorRT FP16 engine or output validation"})
    metadata = {"base_commit":BASE_COMMIT,"counts":{
        "per_network_structures":[len(SPECS[str(i)]) for i in range(4)],
        "nominal_structure_combinations":len(all_structures),"legal_structure_combinations":31,
        "rejected_structure_combinations":5,"legal_physical_assignments":161,
        "evaluated_symmetry_classes":81,"frequency_sequences_per_deployment":len(OPPS)**4,
        "nominal_joint_space_per_condition":161*len(OPPS)**4,
        "symmetry_reduced_joint_space_per_condition":81*len(OPPS)**4},
        "symmetry_numerical_checks":symmetry,
        "symmetry_argument":"Global swap of both DLA queues and thermal coordinates preserves event times, total energy, deadlines and joint peak limits. Each same-time completion is enqueued before dispatch; FIFO keys contain no resource label. This reduction requires the checked symmetric platform and does not identify different relative DLA allocations.",
        "source_files_sha256":{str(p.relative_to(ROOT)).replace("\\","/"):sha256(p.read_bytes()).hexdigest()
                               for p in (BASE_FILE,PLATFORM_FILE,PLATFORM_DIR/"profiles.py",PLATFORM_DIR/"events.py")},
        "per_network_candidates":specs_metadata,"search_order":order,
        "order_rule":"A,C first, then round-robin v3_E/v3_A36/v3_C36_78 with ascending stable ID within each stratum",
        "deployments":deployments,"physical_aliases":aliases,"rejected_structures":rejected,
        "excluded_candidates":[{"id":"v3_A78","reason":"Merging two DLA stages needs separate engine capacity/support evidence; not admitted."},
                               {"id":"new_B_or_D","reason":"No sufficiently specific source-bounded cuts selected; auditing Table 3 does not require populating every structure."}],
        "legality_boundary":"Synthetic legality only. Per-engine TensorRT loadable, CBUF/layout restrictions and output accuracy are not validated. GPU fallback is not silently added."}
    return frozen, metadata


