function thv_export(folder,trials,results)
summary={}; modes={}; earliest={}; witnesses={}; labels='LH';
for k=1:numel(trials)
    tr=trials(k); r=results{k}; c=tr.case; h=tr.thermal;
    if ~strcmp(r.status,'completed'), continue; end
    bestcodes={};
    for j=r.optimal_mode_indices, bestcodes{end+1}=labels(r.modes(j).mode); end
    early_best_safe=0;
    for z=r.earliest
        opt=ismember(z.index,r.reference.optimal_indices);
        early_best_safe=early_best_safe+(opt && strcmp(z.evaluation.status,'safe'));
        earliest(end+1,:)=[{tr.id,z.index,labels(z.modes),opt,z.evaluation.status}, ...
            num2cell(z.evaluation.peak),num2cell(z.evaluation.peak_time), ...
            {sprintf('%d%d',z.schedule.cpu_order),sprintf('%d%d',z.schedule.npu_order)}, ...
            num2cell(z.schedule.start)];
    end
    for m=r.modes
        peaks=[nan nan]; at=peaks; terminal=peaks;
        if strcmp(m.status,'feasible')
            peaks=m.evaluation.peak; at=m.evaluation.peak_time; terminal=m.evaluation.terminal;
            s=m.witness;
            witnesses(end+1,:)=[{tr.id,labels(m.mode),m.witness_kind, ...
                sprintf('%d%d',s.cpu_order),sprintf('%d%d',s.npu_order)}, ...
                num2cell(s.start),num2cell(s.finish),{m.energy},num2cell(peaks),num2cell(at),num2cell(terminal)];
        end
        modes(end+1,:)=[{tr.id,labels(m.mode),m.energy,m.status,m.reason,m.evaluated, ...
            m.unresolved_count,m.earliest_safe,m.witness_kind},num2cell(peaks),num2cell(at),num2cell(terminal)];
    end
    summary(end+1,:)={tr.id,tr.role,c.id,h.initial(1),h.initial(2),h.g,h.grid, ...
        r.reference.best,cv_mode_codes(r.reference),early_best_safe,r.best_found, ...
        strjoin(sort(bestcodes),'|'),r.all_modes_resolved,r.recovered_lower_bound,r.elapsed_s, ...
        sum([r.modes.evaluated])};
end
writetable(cell2table(summary,'VariableNames',{'trial','role','case_id','T0_CPU','T0_NPU', ...
    'g_coupling','grid_s','no_heat_best_J','no_heat_modes','optimal_earliest_safe_count', ...
    'best_found_J','best_found_modes','all_modes_resolved','recovered_no_heat_lower_bound', ...
    'elapsed_s','thermal_evaluations'}),fullfile(folder,'summary.csv'));
writetable(cell2table(modes,'VariableNames',{'trial','modes','energy_J','status','reason', ...
    'evaluations','unresolved_candidates','earliest_safe_count','witness_kind', ...
    'peak_CPU_C','peak_NPU_C','peak_time_CPU_s','peak_time_NPU_s','terminal_CPU_C','terminal_NPU_C'}),fullfile(folder,'modes.csv'));
writetable(cell2table(earliest,'VariableNames',{'trial','reference_index','modes','no_heat_optimal', ...
    'thermal_status','peak_CPU_C','peak_NPU_C','peak_time_CPU_s','peak_time_NPU_s', ...
    'cpu_order','npu_order','start_CA_s','start_CB_s','start_NA_s','start_NB_s'}),fullfile(folder,'earliest.csv'));
writetable(cell2table(witnesses,'VariableNames',{'trial','modes','kind','cpu_order','npu_order', ...
    'start_CA_s','start_CB_s','start_NA_s','start_NB_s','end_CA_s','end_CB_s','end_NA_s','end_NB_s', ...
    'energy_J','peak_CPU_C','peak_NPU_C','peak_time_CPU_s','peak_time_NPU_s', ...
    'terminal_CPU_C','terminal_NPU_C'}),fullfile(folder,'witnesses.csv'));
end
