function trials=p47_cases(path)
% Read only raw common/cases. Never expose predeclared actions or witnesses.
r=jsondecode(fileread(path)); b=r.common;
assert(b.budgets_s.reference_total_per_case==60 && b.budgets_s.C1_total_per_case==60 && b.budgets_s.full_suffix_witness_total_per_case==60);
assert(b.cpu_units_identical && numel(b.cpu_units)==2 && numel(b.npu_units)==1);
assert(~b.preemption && ~b.migration && ~b.frequency_change_during_stage);
assert(strcmp(b.frequency_change_rule,'only_when_entire_domain_idle'));
trials=struct('id',{},'role',{},'case',{},'thermal',{});
for k=1:numel(r.cases)
    if iscell(r.cases), z=r.cases{k}; else, z=r.cases(k); end
    members=string(z.cpu_domains); assert(numel(members)==2 && all(ismember(["C1","C2"],members)),'Only declared single shared domain supported');
    c=struct('id',z.id,'window',b.window_s,'grid',b.start_grid_s,'release',[b.arrival_s.A b.arrival_s.B], ...
        'deadline',[z.deadline_s.A z.deadline_s.B],'q',b.frequency_ratios.L, ...
        'dref',[b.cpu_response.A1.d_ref_s b.cpu_response.B1.d_ref_s], ...
        'alpha',[z.alpha.A1 z.alpha.B1],'u',[b.cpu_response.A1.u_W b.cpu_response.B1.u_W], ...
        'v',[b.cpu_response.A1.v_W b.cpu_response.B1.v_W], ...
        'n',[z.npu_duration_s.A2 z.npu_duration_s.B2], ...
        'npu_increment',[b.npu_active_increment_W.A2 b.npu_active_increment_W.B2], ...
        'idle_cpu',b.base_power_W.cpu_total,'idle_npu',b.base_power_W.npu, ...
        'external',b.base_power_W.outside_thermal_boundary,'time_tol',b.tolerances.time_s, ...
        'energy_abs_tol',b.tolerances.energy_abs_J,'energy_rel_tol',b.tolerances.energy_relative, ...
        'budget_s',b.budgets_s.C1_total_per_case,'domain',[1 1]);
    a=b.thermal;
    h=struct('ambient',a.ambient_degC,'limit',a.limits_degC(:)', ...
        'g_env',a.environment_conductance_W_per_K(:)','g',a.coupling_conductance_W_per_K, ...
        'capacity',a.heat_capacity_J_per_K(:)','initial',z.initial_temperature_degC(:)', ...
        'band',b.tolerances.temperature_band_degC,'grid',c.grid,'budget_s',c.budget_s);
    trials(end+1)=struct('id',z.id,'role',z.role,'case',c,'thermal',h); %#ok<AGROW>
end
end
