function p78_export(folder)
% Export saved repeated calls only; never solve, enumerate, or repair.
% Audited result.upper_J/result.schedule are authoritative. Late raw outputs
% stay in diagnostics and never become a budget-admissible safety witness.
a=load(fullfile(folder,'results.mat'));
assert(isfield(a,'trials') && isfield(a,'records') && iscell(a.records), ...
 'p78:exportInput','results.mat must contain trials and cell records');
records=a.records(:);assert(~isempty(records),'p78:exportInput','No records to export');
summaryRows=cell(numel(records),1);checkRows=summaryRows;costRows=summaryRows;
seenCalls=[];
for k=1:numel(records)
 rec=records{k};assert(isstruct(rec) && isscalar(rec),'p78:exportInput','Invalid record %d',k);
 ti=integerfield(rec,'trial_index',1);rep=integerfield(rec,'repeat',0);
 call=integerfield(rec,'call_index',0);method=char(string(rec.method));
 assert(ti<=numel(a.trials),'p78:exportInput','Unknown trial_index at record %d',k);
 assert(~ismember(call,seenCalls),'p78:exportInput','Duplicate call_index %d',call);
 seenCalls(end+1)=call; %#ok<AGROW>
 tr=a.trials(ti);c=tr.case;h=tr.thermal;r=rec.result;
 assert(isstruct(r) && isscalar(r) && isfield(r,'schedule') && isfield(r,'common_L0_J'), ...
  'p78:exportInput','Record %d lacks audited result fields',k);
 id=char(string(tr.id));cohort=char(string(tr.cohort));baseId=char(string(tr.base_id));
 initial=reshape(h.initial,1,[]);
 assert(numel(initial)==2 && all(isfinite(initial)),'p78:exportInput','Expected two initial temperatures');
 initialMeta=fieldvalue(tr,'initial_C',initial);
 assert(isnumeric(initialMeta) && isvector(initialMeta) && all(isfinite(initialMeta(:))) && ...
  ismember(numel(initialMeta),[1 2]),'p78:exportInput','Invalid initial_C metadata');
 initialLevel=NaN;if all(initialMeta(:)==initialMeta(1)),initialLevel=initialMeta(1);end
 U=scalarfield(r,'upper_J',NaN);L=scalarfield(r,'lower_J',NaN);
 L0=scalarfield(r,'common_L0_J',NaN);sb=scalarfield(r,'solver_bound_J',NaN);
 first=pairfield(r,'first_safe_interval_s',[NaN NaN]);
 offset=pairfield(r,'time_origin_offset_interval_s',[NaN NaN]);
 safe=false;checked=false;passed=NaN;verifiedEnergy=NaN;
 peakLower=[NaN NaN];peakUpper=peakLower;energyError=NaN;upperError=NaN;
 checkStatus='not_checked_no_witness';
 note='No saved budget-admissible witness; no schedule check performed';
 % Emit an empty, headed schedule CSV for calls without a retained witness.
 scheduleTable=table(cell(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
  zeros(0,1),zeros(0,1),zeros(0,1),'VariableNames', ...
  {'stage','choice','unit','mode','start_s','finish_s','duration_s','increment_W'});
 if ~isempty(r.schedule)
  s=r.schedule;checked=true;v=s55_validate(c,s);
  assert(v.feasible,'p78:postcheck','Call %d (%s / %s): invalid schedule (%s)',call,id,method,v.reason);
  e=s55_energy(c,s);th=b64_thermal(c,s,h);
  safe=strcmp(th.status,'safe');energyError=e.error_J;upperError=abs(e.sum_J-U);
  assert(safe && isfinite(U) && energyError<1e-12 && upperError<1e-12, ...
   'p78:postcheck','Call %d failed independent saved-witness checks',call);
  assert(~logical(scalarfield(r,'budget_evidence_ambiguous',false)), ...
   'p78:postcheck','Call %d retains a witness marked budget ambiguous',call);
  verifiedEnergy=e.sum_J;peakLower=reshape(th.peak_lower,1,[]);peakUpper=reshape(th.peak_upper,1,[]);
  assert(numel(peakLower)==2 && numel(peakUpper)==2,'p78:postcheck','Expected two thermal nodes');
  passed=1;checkStatus='verified_safe_witness';
  note='Complete legality, energy sum/integral, continuous thermal envelope including tail';
  scheduleTable=table(c.stage_id(:),s.choice(:),s.unit(:),s.mode(:),s.start(:), ...
   s.finish(:),s.duration(:),s.increment(:),'VariableNames',scheduleTable.Properties.VariableNames);
 else
  assert(~isfinite(U),'p78:postcheck','Call %d has finite U without a saved schedule',call);
 end
 writetable(scheduleTable,fullfile(folder,sprintf('schedule_call_%03d.csv',call)));
 stats=fieldvalue(r,'stats',struct());cost=fieldvalue(r,'cost_s',struct());
 cuts=scalarfield(stats,'cuts',0);events=fieldvalue(r,'events',{});
 [distinct,firstStatus,uniqueEvents,eventCount]=candidateinfo(events);
 summaryRows{k}=struct('call_index',call,'trial_index',ti,'case_id',id,'cohort',cohort, ...
  'base_id',baseId,'initial_C',initialLevel,'initial_cpu_C',initial(1),'initial_npu_C',initial(2), ...
  'rep',rep,'method',method,'reported_method',fieldvalue(r,'method',method), ...
  'status',r.status,'raw_method_status',fieldvalue(r,'raw_method_status',r.status), ...
  'safe',safe,'energy_mJ',U*1000,'certified_lower_mJ',L*1000,'common_L0_mJ',L0*1000, ...
  'solver_bound_mJ',sb*1000, ...
  'independent_optimal',logical(scalarfield(r,'optimal_value_proved',false)), ...
  'independent_infeasible',logical(scalarfield(r,'grid_infeasible_proved',false)), ...
  'elapsed_s',scalarfield(r,'elapsed_s',NaN),'first_safe_s',first(1),'first_safe_upper_s',first(2), ...
  'final_status_within_budget',logical(scalarfield(r,'final_status_within_budget',false)), ...
  'final_solver_bound_within_budget',logical(scalarfield(r,'final_solver_bound_within_budget',false)), ...
  'budget_evidence_ambiguous',logical(scalarfield(r,'budget_evidence_ambiguous',false)), ...
  'has_late_output',~isempty(fieldvalue(r,'budget_late_output',[])), ...
  'input_setup_s',scalarfield(r,'input_setup_s',NaN), ...
  'rounds',scalarfield(stats,'rounds',0),'candidates',scalarfield(stats,'candidates',0), ...
  'logged_candidate_events',eventCount,'distinct_candidates',distinct, ...
  'first_distinct_candidate_thermal_status',firstStatus, ...
  'cache_hits',scalarfield(stats,'cache_hits',0),'thermal_calls',scalarfield(stats,'thermal_calls',0), ...
  'cuts',cuts,'thermal_rows',scalarfield(stats,'thermal_rows',0), ...
  'no_goods',scalarfield(stats,'no_goods',cuts),'fallbacks',scalarfield(stats,'fallbacks',0), ...
  'duplicate_rows',scalarfield(stats,'duplicate_rows',0), ...
  'row_violations',scalarfield(stats,'row_violations',0),'row_unresolved',scalarfield(stats,'row_unresolved',0), ...
  'callbacks',scalarfield(stats,'callbacks',0),'bound_conflicts',scalarfield(stats,'bound_conflicts',0), ...
  'cpu_peak_lower_C',peakLower(1),'cpu_peak_upper_C',peakUpper(1), ...
  'npu_peak_lower_C',peakLower(2),'npu_peak_upper_C',peakUpper(2));
 checkRows{k}=struct('call_index',call,'trial_index',ti,'case_id',id,'cohort',cohort, ...
  'base_id',baseId,'rep',rep,'method',method,'checked',checked,'passed',passed, ...
  'status',checkStatus,'safe',safe,'energy_mJ',verifiedEnergy*1000, ...
  'energy_sum_integral_error_J',energyError,'saved_upper_error_J',upperError, ...
  'cpu_peak_lower_C',peakLower(1),'cpu_peak_upper_C',peakUpper(1), ...
  'npu_peak_lower_C',peakLower(2),'npu_peak_upper_C',peakUpper(2),'note',note);
 costRows{k}=struct('call_index',call,'trial_index',ti,'case_id',id,'cohort',cohort, ...
  'base_id',baseId,'rep',rep,'method',method,'elapsed_s',scalarfield(r,'elapsed_s',NaN), ...
  'input_setup_s',scalarfield(r,'input_setup_s',NaN),'build_s',scalarfield(cost,'build',0), ...
  'solver_inclusive_s',scalarfield(cost,'solver_inclusive',0),'thermal_s',scalarfield(cost,'thermal',0), ...
  'decode_s',scalarfield(cost,'decode',0),'cut_s',scalarfield(cost,'cut',0), ...
  'row_check_s',scalarfield(cost,'row_check',0), ...
  'accounting','Overlapping timers: solver_inclusive includes callbacks; do not sum columns');
 bt=tracematrix(r,'bound_trace',3);st=tracematrix(r,'solver_trace',6);
 % These are raw stored traces, potentially containing late evidence.
 % Their upper column is deliberately not named a budget-valid safe bound.
 writetable(array2table(bt,'VariableNames', ...
  {'elapsed_lower_estimate_s','stored_lower_units','stored_upper_units'}), ...
  fullfile(folder,sprintf('bounds_units_call_%03d.csv',call)));
 writetable(array2table(st,'VariableNames', ...
  {'elapsed_lower_estimate_s','round','solver_lower_units','solver_fval_units','relative_gap','numnodes'}), ...
  fullfile(folder,sprintf('solver_trace_units_call_%03d.csv',call)));
 details=struct('call_index',call,'trial_index',ti,'case_id',id,'cohort',cohort, ...
  'base_id',baseId,'initial_C',initialMeta,'initial_nodes_C',initial,'repeat',rep,'method',method, ...
  'status',r.status,'raw_method_status',fieldvalue(r,'raw_method_status',r.status), ...
  'trace_time_basis',fieldvalue(r,'trace_time_basis','Stored timestamps; exporter applies no shift'), ...
  'event_time_origin',fieldvalue(r,'event_time_origin','Stored event timestamps; exporter applies no shift'), ...
  'time_origin_offset_interval_s',offset,'first_safe_interval_s',first, ...
  'final_status_within_budget',scalarfield(r,'final_status_within_budget',false), ...
  'final_solver_bound_within_budget',scalarfield(r,'final_solver_bound_within_budget',false), ...
  'budget_evidence_ambiguous',scalarfield(r,'budget_evidence_ambiguous',false), ...
  'retained_upper_J',U,'common_L0_J',L0,'reported_solver_bound_J',sb, ...
  'budget_late_output',fieldvalue(r,'budget_late_output',[]), ...
  'late_output_policy','Raw late outputs/traces are diagnostic only; never used to reconstruct retained U', ...
  'energy_unit_J',1/16000, ...
  'candidate_count_scope','Distinct sorted selected sets in logged events; unfinished checks may have no event', ...
  'distinct_candidate_first_events',{uniqueEvents}, ...
  'events',{events},'rounds',{fieldvalue(r,'rounds',{})},'cuts',{fieldvalue(r,'cuts',{})}, ...
  'thermal_rows',{fieldvalue(r,'thermal_rows',{})},'unresolved',fieldvalue(r,'unresolved',[]), ...
  'callback_fields',{fieldvalue(r,'callback_fields',{})}, ...
  'stats',stats,'cost_s',cost,'message',fieldvalue(r,'message',''), ...
  'nonfinite_policy','JSON nonfinite values become null; results.mat remains authoritative');
 writejson(fullfile(folder,sprintf('diagnostics_call_%03d.json',call)),details);
end
writetable(struct2table(vertcat(summaryRows{:})),fullfile(folder,'summary.csv'));
writetable(struct2table(vertcat(checkRows{:})),fullfile(folder,'postchecks.csv'));
writetable(struct2table(vertcat(costRows{:})),fullfile(folder,'cost_diagnostics.csv'));
end

function [n,firstStatus,firstEvents,count]=candidateinfo(events)
if isempty(events),events={};elseif isstruct(events),events=num2cell(events);end
assert(iscell(events),'p78:exportInput','events must be cell or struct');
keys={};firstEvents={};firstStatus='none';count=numel(events);
for i=1:numel(events)
 e=events{i};assert(isstruct(e) && isscalar(e) && isfield(e,'selected'), ...
  'p78:exportInput','Malformed logged candidate event');
 selected=e.selected(:)';
 assert(isnumeric(selected) && ~isempty(selected) && all(isfinite(selected)) && ...
  all(selected==fix(selected)) && all(selected>=1) && numel(unique(selected))==numel(selected), ...
  'p78:exportInput','Invalid selected set in logged event');
 key=sprintf('%d,',sort(selected));
 if ~any(strcmp(keys,key))
  keys{end+1}=key; %#ok<AGROW>
  thermalStatus=char(string(fieldvalue(e,'thermal_status','unknown')));
  firstEvents{end+1}=struct('event_index',i,'selected',selected, ...
   'time_s',scalarfield(e,'time_s',NaN),'round',scalarfield(e,'round',NaN), ...
   'origin',fieldvalue(e,'origin',''),'thermal_status',thermalStatus); %#ok<AGROW>
  if numel(keys)==1,firstStatus=thermalStatus;end
 end
end
n=numel(keys);
end

function x=integerfield(s,name,minimum)
x=scalarfield(s,name,NaN);
assert(isfinite(x) && x==fix(x) && x>=minimum,'p78:exportInput','Invalid %s',name);
end

function x=pairfield(s,name,default)
x=fieldvalue(s,name,default);assert(isnumeric(x) && numel(x)==2,'p78:exportInput','Invalid %s',name);
x=reshape(x,1,2);
end

function x=tracematrix(r,name,width)
x=fieldvalue(r,name,[]);if isempty(x),x=zeros(0,width);end
assert(isnumeric(x) && ismatrix(x) && size(x,2)==width,'p78:exportInput','Unexpected %s shape',name);
end

function x=scalarfield(s,name,default)
x=fieldvalue(s,name,default);
assert((isnumeric(x) || islogical(x)) && isscalar(x),'p78:exportInput','Expected scalar %s',name);
end

function x=fieldvalue(s,name,default)
if isstruct(s) && isscalar(s) && isfield(s,name) && ~isempty(s.(name)),x=s.(name);else,x=default;end
end

function writejson(path,value)
encoded=jsonencode(value,'PrettyPrint',true);
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'p78:exportIO','Cannot open %s',path);
guard=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',encoded);
end
