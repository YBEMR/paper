function trials=c44_cases(path)
raw=jsondecode(fileread(path)); b=raw.common;
trials=struct('id',{},'role',{},'case',{},'thermal',{});
for k=1:numel(raw.cases)
    if iscell(raw.cases), z=raw.cases{k}; else, z=raw.cases(k); end
    c=struct('id',z.id,'window',b.window_s,'grid',b.start_grid_s, ...
        'release',[zget(b.arrival_s,'A') zget(b.arrival_s,'B')], ...
        'deadline',[z.deadline_s.A z.deadline_s.B], ...
        'q',b.frequency_ratios.L,'dref',[b.cpu_response.A1.d_ref_s b.cpu_response.B1.d_ref_s], ...
        'alpha',[z.alpha.A1 z.alpha.B1],'u',[b.cpu_response.A1.u_W b.cpu_response.B1.u_W], ...
        'v',[b.cpu_response.A1.v_W b.cpu_response.B1.v_W], ...
        'n',[z.npu_duration_s.A2 z.npu_duration_s.B2], ...
        'npu_increment',[b.npu_active_increment_W.A2 b.npu_active_increment_W.B2], ...
        'idle_cpu',b.base_power_W.cpu_total,'idle_npu',b.base_power_W.npu, ...
        'external',b.base_power_W.outside_thermal_boundary, ...
        'time_tol',b.tolerances.time_s,'energy_abs_tol',b.tolerances.energy_abs_J, ...
        'energy_rel_tol',b.tolerances.energy_relative,'budget_s',60,'domain',[1 1]);
    % JSON may decode equal-length nested arrays as a matrix or cell array.
    assert(b.budgets_s.reference_total_per_case==60 && b.budgets_s.C0_total_per_case==60 && b.budgets_s.C1_total_per_case==60);
    % Derive domain labels from declared membership, never from case-specific decisions.
    domains=z.cpu_domains;
    if iscell(domains) && numel(domains)==2 && all(cellfun(@ischar,domains(:)))
        c.domain=[1 1];
    elseif iscell(domains)
        c.domain=zeros(1,2);
        for d=1:numel(domains)
            members=string(domains{d});
            for u=1:2, if any(members=="C"+u), c.domain(u)=d; end, end
        end
        assert(all(c.domain>0));
    elseif isstring(domains)
        error('c44:input','Unexpected domain encoding');
    else
        error('c44:input','Unknown domain encoding');
    end
    th=b.thermal;
    h=struct('ambient',th.ambient_degC,'limit',th.limits_degC(:)', ...
        'g_env',th.environment_conductance_W_per_K(:)','g',th.coupling_conductance_W_per_K, ...
        'capacity',th.heat_capacity_J_per_K(:)','initial',z.initial_temperature_degC(:)', ...
        'band',b.tolerances.temperature_band_degC,'grid',c.grid,'budget_s',60);
    trials(end+1)=struct('id',z.id,'role',z.role,'case',c,'thermal',h); %#ok<AGROW>
end
end
function x=zget(z,k), x=z.(k); end
